export function buildIndustryPresentation(config) {
  const key = config.key === 'other' ? 'generic_business' : config.key;
  const terms = config.terminology;
  const fields = config.contactFields;
  const common = new Set(['fullName','phoneNumber','email','city','leadSource','leadStatus','priority','notes','whatsappConsentStatus','followUpDate']);
  const domainFields = fields.filter(f => !common.has(f.key));
  const interestField = fields.find(f => f.key === 'interestedPropertyType') || domainFields.find(f => /interest|serviceNeeded|destination|roomPreference/i.test(f.key)) || domainFields[0];
  const projectField = fields.find(f => f.key === 'interestedProject') || fields.find(f => /branchName|productCategory|companyName|vehicleModel|travelScope|issueDescription|stayPurpose/.test(f.key));
  const options = field => (field?.options || []).map(o => typeof o === 'object' ? o.value : o);
  return {
    ...presentation.metadata[key],
    libraryLabel: presentation.metadata[key]?.libraryLabel || config.displayLabel + ' Preset Library',
    templatePlaceholder: presentation.metadata[key]?.templatePlaceholder || 'e.g. customer_enquiry_followup',
    quickReplyPlaceholder: presentation.metadata[key]?.quickReplyPlaceholder || terms.interestFieldLabel,
    qrCategories: ['all', ...new Set((config.quickReplyPresets || []).map(q => q.category || 'General'))],
    variableHints: (config.supportedVariables || []).map(v => '{{' + v.token + '}}').join(', '),
    dashboard: presentation.dashboard[key] || {subtitle: 'Manage ' + terms.leadPlural.toLowerCase() + ', follow-ups and campaign activity.',importHint: 'Upload contacts from XLSX or CSV',templateHint: config.description,campaignHint: 'Plan an audience snapshot and schedule',scheduleHint: 'Plan your next follow-up when you are ready.'},
    contacts: {subtitle: 'Manage ' + terms.leadPlural.toLowerCase() + ' and build campaign audiences.',databaseFoot: config.displayLabel + ' contact database',interestFilterLabel: 'All ' + terms.offeringPlural,interestColumnLabel: terms.interestFieldLabel,projectColumnLabel: projectField?.label || terms.categoryLabel || 'Category',profileEyebrow: terms.leadLabel.toUpperCase(),requirementsTitle: terms.interestFieldLabel + ' & Requirements',emptyImportHint: 'Import a contact sheet or add your first contact manually.',...presentation.contacts[key],interestOptions: options(interestField)},
    contactBindings: {interest: interestField?.key, project: projectField?.key},
    campaigns: presentation.campaigns[key] || {goals: [...new Set((config.sampleCampaignDrafts || []).map(c => c.goal).filter(Boolean)), 'Other'],categories: [...new Set(config.templateCategories || []), 'Other']},
    inboxSubtitle: 'Manage ' + terms.leadPlural.toLowerCase() + ', customer replies and messaging automation.',
    contactAction: ['real_estate', 'education'].includes(key)
      ? { to: '/import', icon: 'FileSpreadsheet', title: 'Import Contacts', text: 'Upload contacts from XLSX or CSV' }
      : { to: '/contacts', icon: 'ContactRound', title: 'Add ' + terms.leadLabel, text: 'Record and manage ' + terms.leadPlural.toLowerCase() },
  };
}
